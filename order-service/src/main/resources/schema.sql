CREATE TABLE IF NOT EXISTS orders (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, customer_id VARCHAR(64) NOT NULL, product_id BIGINT NOT NULL, quantity INT NOT NULL, status VARCHAR(30) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_summary (
  order_id BIGINT PRIMARY KEY, customer_id VARCHAR(64) NOT NULL, product_id BIGINT NOT NULL, quantity INT NOT NULL, status VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS outbox_events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, event_type VARCHAR(100) NOT NULL, payload JSON NOT NULL, published BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
